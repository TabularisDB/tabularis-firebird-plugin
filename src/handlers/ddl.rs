//! Firebird SQL builders; these never connect or execute SQL.
use super::crud::identifier;
use crate::{
    client::Client,
    error::PluginError,
    models::{inner_params, ConnectionParams},
    rpc::{error_response, ok_response},
};
use serde_json::{json, Value};

fn text<'a>(value: &'a Value, key: &str) -> Result<&'a str, PluginError> {
    value
        .get(key)
        .and_then(Value::as_str)
        .filter(|v| !v.is_empty())
        .ok_or_else(|| PluginError::invalid_params(format!("{key} is required")))
}
fn name(value: &Value, key: &str) -> Result<String, PluginError> {
    identifier(text(value, key)?)
}
fn flag(value: &Value, key: &str) -> Result<bool, PluginError> {
    match value.get(key) {
        None | Some(Value::Null) => Ok(false),
        Some(Value::Bool(v)) => Ok(*v),
        _ => Err(PluginError::invalid_params(format!(
            "{key} must be boolean"
        ))),
    }
}
fn list(value: &Value, key: &str) -> Result<Vec<String>, PluginError> {
    let values = value
        .get(key)
        .and_then(Value::as_array)
        .filter(|v| !v.is_empty())
        .ok_or_else(|| PluginError::invalid_params(format!("{key} must be a non-empty array")))?;
    values
        .iter()
        .map(|v| {
            v.as_str()
                .ok_or_else(|| PluginError::invalid_params("Column names must be strings"))
                .and_then(identifier)
        })
        .collect()
}
fn literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

fn fragment(value: &str) -> Result<String, PluginError> {
    let mut quoted = false;
    let bytes = value.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'\'' {
            if quoted && bytes.get(i + 1) == Some(&b'\'') {
                i += 2;
                continue;
            }
            quoted = !quoted;
        } else if !quoted
            && (bytes[i] == b';'
                || bytes[i] == 0
                || bytes.get(i..i + 2) == Some(b"--")
                || bytes.get(i..i + 2) == Some(b"/*"))
        {
            return Err(PluginError::invalid_params(
                "SQL fragments must not contain statement separators or comments",
            ));
        }
        i += 1;
    }
    if quoted || value.trim().is_empty() {
        return Err(PluginError::invalid_params("Invalid SQL fragment"));
    }
    Ok(value.trim().into())
}

fn column(value: &Value) -> Result<String, PluginError> {
    let column = name(value, "name")?;
    let data_type = fragment(text(value, "data_type")?)?;
    let mut sql = format!("{column} {data_type}");
    if flag(value, "is_auto_increment")? {
        sql.push_str(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if let Some(default) = value
        .get("default_value")
        .and_then(Value::as_str)
        .filter(|s| !s.trim().is_empty())
    {
        if flag(value, "is_auto_increment")? {
            return Err(PluginError::invalid_params(
                "An identity column cannot also have a default",
            ));
        }
        let default = default.trim();
        let default = if default
            .get(..8)
            .is_some_and(|s| s.eq_ignore_ascii_case("DEFAULT "))
        {
            &default[8..]
        } else {
            default
        };
        sql.push_str(&format!(" DEFAULT {}", fragment(default)?));
    }
    if !value
        .get("is_nullable")
        .and_then(Value::as_bool)
        .unwrap_or(true)
        || flag(value, "is_pk")?
    {
        sql.push_str(" NOT NULL");
    }
    Ok(sql)
}

fn comment(table: &str, column: &str, value: &Value) -> Option<String> {
    value
        .get("comment")
        .and_then(Value::as_str)
        .map(|v| format!("COMMENT ON COLUMN {table}.{column} IS {}", literal(v)))
}

fn build(method: &str, p: &Value) -> Result<Vec<String>, PluginError> {
    match method {
        "get_create_table_sql" => {
            let table = name(p, "table_name")?;
            let columns = p
                .get("columns")
                .and_then(Value::as_array)
                .filter(|c| !c.is_empty())
                .ok_or_else(|| PluginError::invalid_params("columns must be a non-empty array"))?;
            let mut definitions = columns.iter().map(column).collect::<Result<Vec<_>, _>>()?;
            let keys = columns
                .iter()
                .filter(|c| c.get("is_pk") == Some(&Value::Bool(true)))
                .map(|c| name(c, "name"))
                .collect::<Result<Vec<_>, _>>()?;
            if !keys.is_empty() {
                definitions.push(format!("PRIMARY KEY ({})", keys.join(", ")));
            }
            let mut statements = vec![format!(
                "CREATE TABLE {table} (\n  {}\n)",
                definitions.join(",\n  ")
            )];
            for c in columns {
                if let Some(sql) = comment(&table, &name(c, "name")?, c) {
                    statements.push(sql);
                }
            }
            Ok(statements)
        }
        "get_add_column_sql" => {
            let table = name(p, "table")?;
            let value = p
                .get("column")
                .ok_or_else(|| PluginError::invalid_params("column is required"))?;
            if flag(value, "is_pk")? {
                return Err(PluginError::invalid_params(
                    "Adding a primary key requires an explicit ALTER TABLE statement",
                ));
            }
            let mut statements = vec![format!("ALTER TABLE {table} ADD {}", column(value)?)];
            if let Some(sql) = comment(&table, &name(value, "name")?, value) {
                statements.push(sql);
            }
            Ok(statements)
        }
        "get_alter_column_sql" => {
            let table = name(p, "table")?;
            let old = p
                .get("old_column")
                .ok_or_else(|| PluginError::invalid_params("old_column is required"))?;
            let new = p
                .get("new_column")
                .ok_or_else(|| PluginError::invalid_params("new_column is required"))?;
            if flag(old, "is_pk")? != flag(new, "is_pk")?
                || flag(old, "is_auto_increment")? != flag(new, "is_auto_increment")?
            {
                return Err(PluginError::invalid_params(
                    "Changing primary-key or identity status requires explicit ALTER TABLE SQL",
                ));
            }
            let mut statements = vec![];
            let old_name = name(old, "name")?;
            let new_name = name(new, "name")?;
            if old_name != new_name {
                statements.push(format!(
                    "ALTER TABLE {table} ALTER {old_name} TO {new_name}"
                ));
            }
            if old.get("data_type") != new.get("data_type") {
                statements.push(format!(
                    "ALTER TABLE {table} ALTER {new_name} TYPE {}",
                    fragment(text(new, "data_type")?)?
                ));
            }
            if old.get("is_nullable") != new.get("is_nullable") {
                let action = if new.get("is_nullable") == Some(&Value::Bool(false)) {
                    "SET"
                } else {
                    "DROP"
                };
                statements.push(format!(
                    "ALTER TABLE {table} ALTER {new_name} {action} NOT NULL"
                ));
            }
            if old.get("default_value") != new.get("default_value") {
                let default = new
                    .get("default_value")
                    .and_then(Value::as_str)
                    .filter(|s| !s.trim().is_empty());
                let action = if let Some(v) = default {
                    let v = v.trim();
                    let v = if v
                        .get(..8)
                        .is_some_and(|s| s.eq_ignore_ascii_case("DEFAULT "))
                    {
                        &v[8..]
                    } else {
                        v
                    };
                    format!("SET DEFAULT {}", fragment(v)?)
                } else {
                    "DROP DEFAULT".into()
                };
                statements.push(format!("ALTER TABLE {table} ALTER {new_name} {action}"));
            }
            if old.get("comment") != new.get("comment") {
                statements.push(format!(
                    "COMMENT ON COLUMN {table}.{new_name} IS {}",
                    new.get("comment")
                        .and_then(Value::as_str)
                        .map(literal)
                        .unwrap_or_else(|| "NULL".into())
                ));
            }
            Ok(statements)
        }
        "get_create_index_sql" => Ok(vec![format!(
            "CREATE {}INDEX {} ON {} ({})",
            if flag(p, "is_unique")? { "UNIQUE " } else { "" },
            name(p, "index_name")?,
            name(p, "table")?,
            list(p, "columns")?.join(", ")
        )]),
        "get_create_foreign_key_sql" => {
            let columns = if p.get("columns").is_some() {
                list(p, "columns")?
            } else {
                vec![name(p, "column")?]
            };
            let references = if p.get("ref_columns").is_some() {
                list(p, "ref_columns")?
            } else {
                vec![name(p, "ref_column")?]
            };
            if columns.len() != references.len() {
                return Err(PluginError::invalid_params(
                    "Foreign-key column counts differ",
                ));
            }
            let mut sql = format!(
                "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
                name(p, "table")?,
                name(p, "fk_name")?,
                columns.join(", "),
                name(p, "ref_table")?,
                references.join(", ")
            );
            for (key, event) in [("on_update", "UPDATE"), ("on_delete", "DELETE")] {
                if let Some(action) = p.get(key).and_then(Value::as_str).filter(|s| !s.is_empty()) {
                    let action = action.to_ascii_uppercase();
                    let action = if action == "RESTRICT" {
                        "NO ACTION"
                    } else {
                        &action
                    };
                    if !["NO ACTION", "CASCADE", "SET NULL", "SET DEFAULT"].contains(&action) {
                        return Err(PluginError::invalid_params(
                            "Unsupported foreign-key action",
                        ));
                    }
                    sql.push_str(&format!(" ON {event} {action}"));
                }
            }
            Ok(vec![sql])
        }
        _ => Err(PluginError::invalid_params("Unknown SQL builder")),
    }
}

pub fn generate(id: Value, p: &Value, method: &str) -> Value {
    match build(method, p) {
        Ok(sql) => ok_response(id, json!(sql)),
        Err(error) => error_response(id, error.code, &error.message),
    }
}
pub fn get_create_table_sql(id: Value, p: &Value) -> Value {
    generate(id, p, "get_create_table_sql")
}
pub fn get_add_column_sql(id: Value, p: &Value) -> Value {
    generate(id, p, "get_add_column_sql")
}
pub fn get_alter_column_sql(id: Value, p: &Value) -> Value {
    generate(id, p, "get_alter_column_sql")
}
pub fn get_create_index_sql(id: Value, p: &Value) -> Value {
    generate(id, p, "get_create_index_sql")
}
pub fn get_create_foreign_key_sql(id: Value, p: &Value) -> Value {
    generate(id, p, "get_create_foreign_key_sql")
}

pub fn mutate(id: Value, p: &Value, method: &str) -> Value {
    let result = (|| {
        let sql = match method {
            "drop_index" => format!("DROP INDEX {}", name(p, "index_name")?),
            "drop_foreign_key" => format!(
                "ALTER TABLE {} DROP CONSTRAINT {}",
                name(p, "table")?,
                name(p, "fk_name")?
            ),
            "drop_view" => format!("DROP VIEW {}", name(p, "name")?),
            "create_view" | "alter_view" => format!(
                "{} VIEW {} AS {}",
                if method == "create_view" {
                    "CREATE"
                } else {
                    "ALTER"
                },
                name(p, "name")?,
                text(p, "definition")?
            ),
            _ => return Err(PluginError::invalid_params("Unknown mutation")),
        };
        Client::connect(ConnectionParams::from_value(inner_params(p))?)?.execute(
            &sql,
            vec![],
            0,
            None,
            None,
        )?;
        Ok(Value::Null)
    })();
    match result {
        Ok(value) => ok_response(id, value),
        Err(error) => error_response(id, error.code, &error.message),
    }
}
pub fn drop_index(id: Value, p: &Value) -> Value {
    mutate(id, p, "drop_index")
}
pub fn drop_foreign_key(id: Value, p: &Value) -> Value {
    mutate(id, p, "drop_foreign_key")
}
pub fn drop_table_sql(id: Value, p: &Value) -> Value {
    match name(p, "table") {
        Ok(name) => ok_response(id, json!(format!("DROP TABLE {name}"))),
        Err(error) => error_response(id, error.code, &error.message),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    #[ignore = "mutates isolated fixture schema; run tests/live-firebird.ps1"]
    fn live_generated_schema_changes_and_views() {
        let config: Value = serde_json::from_str(
            &std::fs::read_to_string(std::env::var("FIREBIRD_TEST_CONFIG").unwrap()).unwrap(),
        )
        .unwrap();
        let table = format!(
            "FB_D_{:X}_{:X}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_micros() as u32
        );
        let view = format!("V_{table}");
        let index = format!("I_{table}");
        let foreign = format!("F_{table}");
        let execute = |sql: &str| {
            Client::connect(ConnectionParams::from_value(&config).unwrap())
                .unwrap()
                .execute(sql, vec![], 0, None, None)
                .unwrap()
        };
        let statements=build("get_create_table_sql",&json!({"table_name":table,"columns":[{"name":"ID","data_type":"BIGINT","is_pk":true,"is_auto_increment":true},{"name":"LABEL","data_type":"VARCHAR(20)","is_nullable":true,"default_value":"'owner''s value'","comment":"owner's comment"},{"name":"PARENT_ID","data_type":"BIGINT","is_nullable":true}]})).unwrap();
        execute(&statements[0]);
        struct Cleanup(Value, String);
        impl Drop for Cleanup {
            fn drop(&mut self) {
                if let Ok(mut client) =
                    Client::connect(ConnectionParams::from_value(&self.0).unwrap())
                {
                    let _ =
                        client.execute(&format!("DROP VIEW V_{}", self.1), vec![], 0, None, None);
                    let _ =
                        client.execute(&format!("DROP TABLE {}", self.1), vec![], 0, None, None);
                }
            }
        }
        let cleanup = Cleanup(config.clone(), table.clone());
        for sql in &statements[1..] {
            execute(sql);
        }
        for sql in build("get_add_column_sql",&json!({"table":table,"column":{"name":"EXTRA","data_type":"INTEGER","is_nullable":true}})).unwrap(){execute(&sql);}
        for sql in build("get_alter_column_sql",&json!({"table":table,"old_column":{"name":"LABEL","data_type":"VARCHAR(20)","is_nullable":true,"default_value":"DEFAULT 'owner''s value'","comment":"owner's comment"},"new_column":{"name":"TITLE","data_type":"VARCHAR(40)","is_nullable":false,"default_value":"'semi;colon'","comment":"new comment"}})).unwrap(){execute(&sql);}
        for sql in build(
            "get_create_index_sql",
            &json!({"table":table,"index_name":index,"columns":["TITLE"],"is_unique":true}),
        )
        .unwrap()
        {
            execute(&sql);
        }
        for sql in build("get_create_foreign_key_sql",&json!({"table":table,"fk_name":foreign,"column":"PARENT_ID","ref_table":table,"ref_column":"ID","on_delete":"SET NULL","on_update":"CASCADE"})).unwrap(){execute(&sql);}
        execute(&format!(
            "INSERT INTO {} DEFAULT VALUES",
            identifier(&table).unwrap()
        ));
        let result = execute(&format!(
            "SELECT ID,TITLE,EXTRA FROM {}",
            identifier(&table).unwrap()
        ));
        assert_eq!(result["rows"][0][1], "semi;colon");
        let mutation = |method: &str, mut params: Value| {
            params["params"] = config.clone();
            let result = mutate(json!(1), &params, method);
            assert!(result.get("error").is_none(), "{result}");
        };
        mutation(
            "create_view",
            json!({"name":view,"definition":format!("SELECT ID FROM {table}")}),
        );
        mutation(
            "alter_view",
            json!({"name":view,"definition":format!("SELECT ID,TITLE FROM {table}")}),
        );
        assert_eq!(
            execute(&format!("SELECT * FROM {view}"))["columns"],
            json!(["ID", "TITLE"])
        );
        mutation("drop_view", json!({"name":view}));
        mutation("drop_foreign_key", json!({"table":table,"fk_name":foreign}));
        mutation("drop_index", json!({"index_name":index}));
        execute(&format!("DROP TABLE {table}"));
        drop(cleanup);
    }
    #[test]
    fn renders_composite_keys_comments_and_firebird_column_changes() {
        let sql=build("get_create_table_sql",&json!({"table_name":"a\"b","columns":[{"name":"A","data_type":"INTEGER","is_pk":true},{"name":"B","data_type":"INTEGER","is_pk":true,"comment":"owner's key"}]})).unwrap();
        assert!(sql[0].contains("PRIMARY KEY (\"A\", \"B\")"));
        assert!(sql[1].contains("'owner''s key'"));
        assert!(build(
            "get_create_index_sql",
            &json!({"table":"T","index_name":"I","columns":[]})
        )
        .is_err());
        assert!(fragment("INTEGER; DROP TABLE T").is_err());
        assert!(fragment("'semi;colon'").is_ok());
        let sql=build("get_alter_column_sql",&json!({"table":"T","old_column":{"name":"A","data_type":"INTEGER","default_value":"DEFAULT 1"},"new_column":{"name":"B","data_type":"BIGINT","default_value":null}})).unwrap();
        assert_eq!(
            sql,
            vec![
                "ALTER TABLE \"T\" ALTER \"A\" TO \"B\"",
                "ALTER TABLE \"T\" ALTER \"B\" TYPE BIGINT",
                "ALTER TABLE \"T\" ALTER \"B\" DROP DEFAULT"
            ]
        );
    }
}
