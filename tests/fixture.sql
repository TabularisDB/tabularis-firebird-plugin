CREATE DOMAIN FB_LABEL AS VARCHAR(40) DEFAULT 'fallback' NOT NULL;
CREATE TABLE FB_PARENT (
    TENANT_ID INTEGER NOT NULL,
    ID INTEGER NOT NULL,
    CONSTRAINT PK_FB_PARENT PRIMARY KEY (TENANT_ID, ID)
);
CREATE TABLE FB_CHILD (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TENANT_ID INTEGER,
    PARENT_ID INTEGER,
    LABEL FB_LABEL,
    AMOUNT DECIMAL(18,2),
    FLAG BOOLEAN,
    NOTES BLOB SUB_TYPE TEXT,
    CONSTRAINT FK_FB_CHILD_PARENT FOREIGN KEY (TENANT_ID, PARENT_ID)
        REFERENCES FB_PARENT (TENANT_ID, ID) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX IDX_FB_CHILD_LABEL ON FB_CHILD (LABEL, ID);
CREATE INDEX IDX_FB_CHILD_EXPR ON FB_CHILD COMPUTED BY (UPPER(LABEL));
CREATE TABLE "odd' table" ("mixedCase" VARCHAR(12));
CREATE VIEW FB_CHILD_VIEW AS SELECT ID, LABEL FROM FB_CHILD;
CREATE VIEW "odd' view" AS SELECT "mixedCase" FROM "odd' table";
COMMENT ON TABLE FB_CHILD IS 'Fixture table';
COMMENT ON COLUMN FB_CHILD.LABEL IS 'Label comment';
